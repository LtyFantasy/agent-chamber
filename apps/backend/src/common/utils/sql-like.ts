/**
 * 把字面前缀转义成 LIKE 模式片段（`\` `%` `_` 逐字符前置反斜杠）。
 *
 * @param input 用户输入的字面前缀（任意字符串，全定义）
 * @returns 转义后的片段；调用方自行补 `%` 并挂 `ESCAPE '\'`
 */
export function escapeLikePrefix(input: string): string {
  return input.replace(/[\\%_]/g, (ch) => `\\${ch}`);
}
